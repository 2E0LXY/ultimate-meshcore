#!/usr/bin/env python3
"""Make the T-Deck's colour emoji: renders a chosen set from Noto Color Emoji into 16x16 RGB565
bitmaps with a 1-bit mask, written to examples/companion_radio/ui-tdeck/UmcEmoji.h.

    python3 scripts/umc_make_emoji.py [path/to/NotoColorEmoji.ttf]

Needs Pillow. Emoji artwork: Noto Emoji by Google (Apache License 2.0 / SIL OFL 1.1).
To add emoji, add them to PICK (at most 254 in all) and run this again."""
import os, sys
from PIL import Image, ImageDraw, ImageFont

FONT = sys.argv[1] if len(sys.argv) > 1 else "/usr/share/fonts/truetype/noto/NotoColorEmoji.ttf"
OUT = os.path.join(os.path.dirname(__file__), "..", "examples", "companion_radio", "ui-tdeck", "UmcEmoji.h")
PX = 16
# The picker's order: faces, hands, hearts, then things people on a mesh talk about
PICK = ("😀😃😄😁😆😅🤣😂🙂🙃😉😊😇🥰😍🤩😘😋😛😜🤪😝🤗🤭🤫🤔🤨😐😑😶😏😒🙄😬😌😔😪😴😷🤒🤕🤢🤮🤧🥵🥶😵🤯🤠🥳😎🤓🧐"
        "😕😟🙁😮😯😲😳🥺😦😨😰😥😢😭😱😖😣😞😓😩😫🥱😤😡😠🤬😈💀💩🤡👻👽👾🤖"
        "👋🤚✋🖖👌🤏✌🤞🤟🤘🤙👈👉👆👇☝👍👎✊👊👏🙌🤝🙏✍💪👀👣"
        "❤🧡💛💚💙💜🖤🤍💔💕💯💥💫💤💬"
        "☀⛅🌧⛈❄☃🌈⚡🔥💧🌊🌍🌙⭐🌟✨🌲🌳🍀🌸🌻🐕🐈🐦🦆🐑🐄🐎"
        "☕🍺🍻🍷🍕🍔🍟🍰🎂🍫🍎"
        "🏠🏡🏢🏰⛪🏥🚗🚕🚌🚲🚂✈🚁⛵🚢⛰🗼📍🧭"
        "📡📶📻📱💻⌨🔋🔌💡🔦🔧🔨⚙🧲📷📺⏰⌚⏳📞☎📢🔔🔒🔑📦📝📌✏📅"
        "✅❌⚠❓❗➕➖🆗🆘🔴🟠🟡🟢🔵🟣⚫⚪⬆⬇⬅➡🔄♻🎉🎁🏆⚽🎵🎶")
# These are sent with U+FE0F so phones show them in colour
NEEDS_VS16 = set("✌☝✍❤☀⛈❄☃⚡⭐⛅🌧✈⛰⌨⚙☎⏰⌚⏳✏⚠❗❓➕➖⬆⬇⬅➡♻⚫⚪☕⛪⛵")

def render(ch, font):
    img = Image.new("RGBA", (160, 160), (0, 0, 0, 0))
    ImageDraw.Draw(img).text((10, 10), ch + ("\ufe0f" if ch in NEEDS_VS16 else ""), font=font, embedded_color=True)
    box = img.getbbox()
    if not box: return None
    img = img.crop(box); w, h = img.size; s = max(w, h)
    sq = Image.new("RGBA", (s, s), (0, 0, 0, 0)); sq.paste(img, ((s - w) // 2, (s - h) // 2))
    return sq.resize((PX, PX), Image.LANCZOS)

def main():
    font = ImageFont.truetype(FONT, 109)                        # the colour font has one bitmap size
    seen, items = set(), []
    for ch in PICK:
        cp = ord(ch)
        if cp in seen: continue
        seen.add(cp)
        im = render(ch, font)
        if im is None: print("not in the font, skipped:", hex(cp)); continue
        px, mask = [], [0] * (PX * PX // 8)
        for i, (r, g, b, a) in enumerate(im.getdata()):
            if a >= 110:
                if a < 255:                                     # blend the soft edge onto a dark background
                    r, g, b = r * a // 255, g * a // 255, b * a // 255
                mask[i // 8] |= 0x80 >> (i % 8)
            px.append(((r & 0xF8) << 8) | ((g & 0xFC) << 3) | (b >> 3) if a >= 110 else 0)
        items.append((cp, ch in NEEDS_VS16, px, mask))
    if len(items) > 254: sys.exit("at most 254 emoji (they are numbered in one byte)")
    order = sorted(range(len(items)), key=lambda i: items[i][0])  # the lookup table is sorted by codepoint
    rank = {old: new for new, old in enumerate(order)}
    with open(OUT, "w", encoding="utf-8") as f:
        f.write("#pragma once\n// Generated by scripts/umc_make_emoji.py - do not edit by hand.\n"
                "// Colour emoji for the T-Deck: 16x16 RGB565 with a 1-bit mask.\n"
                "// Artwork: Noto Emoji by Google (Apache License 2.0 / SIL OFL 1.1).\n#include <stdint.h>\n\n")
        f.write("#define UMC_EMOJI_PX %d\n#define UMC_EMOJI_COUNT %d\n\n" % (PX, len(items)))
        f.write("// sorted by codepoint; bit 31 set = send it followed by U+FE0F\nstatic const uint32_t kEmojiCp[UMC_EMOJI_COUNT] = {\n")
        f.write(",\n".join("  0x%08X" % (items[i][0] | (0x80000000 if items[i][1] else 0)) for i in order) + "\n};\n\n")
        f.write("// the picker's order (indexes into the tables)\nstatic const uint8_t kEmojiPick[UMC_EMOJI_COUNT] = {%s};\n\n" % ", ".join(str(rank[i]) for i in range(len(items))))
        f.write("static const uint8_t kEmojiMask[UMC_EMOJI_COUNT][%d] = {\n" % (PX * PX // 8))
        f.write(",\n".join("  {%s}" % ",".join(str(b) for b in items[i][3]) for i in order) + "\n};\n\n")
        f.write("static const uint16_t kEmojiPx[UMC_EMOJI_COUNT][%d] = {\n" % (PX * PX))
        f.write(",\n".join("  {%s}" % ",".join("0x%04X" % v for v in items[i][2]) for i in order) + "\n};\n")
    print("%d emoji -> %s" % (len(items), os.path.normpath(OUT)))

if __name__ == "__main__":
    main()
