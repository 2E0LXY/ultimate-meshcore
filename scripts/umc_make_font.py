#!/usr/bin/env python3
"""Turn a TTF into an Adafruit GFX font header.

The stock GFX fonts start at 9pt, which is too wide for a 320x240 screen full of lists -
labels collide and the tab bar runs out of room. This renders a smaller face, with no
anti-aliasing, into the same structure the GFX library expects.

    python scripts/umc_make_font.py --ttf Inter.ttf --size 11 --name UmcSans8 --out UmcFonts.h

Several faces can go into one header by repeating --size/--weight/--name.
"""
import argparse
import sys

FIRST, LAST = 0x20, 0x7E


def render_face(path, px, weight, name):
    from PIL import Image, ImageDraw, ImageFont

    font = ImageFont.truetype(path, px)
    try:
        font.set_variation_by_name(weight)
    except Exception:
        if weight not in ("Regular", ""):
            print(f"  (no '{weight}' axis; using the face as it comes)", file=sys.stderr)
    ascent, descent = font.getmetrics()

    pad = px * 2
    bitmaps = []        # one flat list of bytes for the whole face
    glyphs = []
    for code in range(FIRST, LAST + 1):
        ch = chr(code)
        img = Image.new("1", (px * 4 + pad * 2, px * 4 + pad * 2), 0)
        d = ImageDraw.Draw(img)
        d.fontmode = "1"                       # 1 bit per pixel: no grey edges
        d.text((pad, pad), ch, font=font, fill=1, anchor="la")
        box = img.getbbox()
        advance = int(round(font.getlength(ch)))
        if box is None:                        # a space, or anything with no ink
            glyphs.append((len(bitmaps), 0, 0, advance, 0, 0))
            continue
        x0, y0, x1, y1 = box
        w, h = x1 - x0, y1 - y0
        offset = len(bitmaps)
        # bits run continuously through the glyph, not padded to byte boundaries per row
        bits = []
        px_data = img.load()
        for y in range(y0, y1):
            for x in range(x0, x1):
                bits.append(1 if px_data[x, y] else 0)
        for i in range(0, len(bits), 8):
            byte = 0
            for b in bits[i:i + 8]:
                byte = (byte << 1) | b
            byte <<= 8 - len(bits[i:i + 8])
            bitmaps.append(byte & 0xFF)
        glyphs.append((offset, w, h, advance, x0 - pad, y0 - (pad + ascent)))

    return {
        "name": name,
        "bitmaps": bitmaps,
        "glyphs": glyphs,
        "yAdvance": ascent + descent,
        "ascent": ascent,
        "px": px,
        "weight": weight,
    }


def emit(face):
    out = []
    name = face["name"]
    out.append(f"const uint8_t {name}Bitmaps[] PROGMEM = {{")
    for i in range(0, len(face["bitmaps"]), 12):
        row = ", ".join(f"0x{b:02X}" for b in face["bitmaps"][i:i + 12])
        out.append(f"  {row},")
    out.append("};")
    out.append("")
    out.append(f"const GFXglyph {name}Glyphs[] PROGMEM = {{")
    for code, g in zip(range(FIRST, LAST + 1), face["glyphs"]):
        ch = chr(code)
        shown = "space" if ch == " " else ch
        out.append("  {{ {:5d}, {:3d}, {:3d}, {:3d}, {:4d}, {:4d} }},   // 0x{:02X} {}".format(
            g[0], g[1], g[2], g[3], g[4], g[5], code, shown))
    out.append("};")
    out.append("")
    out.append(f"const GFXfont {name} PROGMEM = {{")
    out.append(f"  (uint8_t*){name}Bitmaps,")
    out.append(f"  (GFXglyph*){name}Glyphs,")
    out.append(f"  0x{FIRST:02X}, 0x{LAST:02X}, {face['yAdvance']} }};")
    out.append("")
    return "\n".join(out)


def main():
    ap = argparse.ArgumentParser(description="Make a GFX font header from a TTF")
    ap.add_argument("--ttf", required=True)
    ap.add_argument("--face", action="append", required=True,
                    help="name:pixels:weight, e.g. UmcSans:11:Regular (repeatable)")
    ap.add_argument("--out", required=True)
    ap.add_argument("--credit", default="", help="licence line for the header comment")
    args = ap.parse_args()

    faces = []
    for spec in args.face:
        name, px, weight = (spec.split(":") + ["Regular"])[:3]
        print(f"rendering {name}: {px}px {weight}")
        faces.append(render_face(args.ttf, int(px), weight, name))

    parts = ["// Generated by scripts/umc_make_font.py - do not edit by hand.",
             "//"]
    if args.credit:
        for line in args.credit.split("\n"):
            parts.append(f"// {line}")
    parts.append("")
    parts.append("#pragma once")
    parts.append("")
    parts.append("#include <Adafruit_GFX.h>")
    parts.append("")
    for f in faces:
        parts.append(f"// {f['name']}: {f['px']}px {f['weight']}, line height {f['yAdvance']}, "
                     f"cap top {f['ascent']} above the baseline")
        parts.append(emit(f))
    with open(args.out, "w", encoding="utf-8") as fh:
        fh.write("\n".join(parts))

    total = sum(len(f["bitmaps"]) for f in faces)
    print(f"{args.out}: {len(faces)} faces, {total} bytes of glyph data")
    for f in faces:
        adv = [g[3] for g in f["glyphs"]]
        lower = [f["glyphs"][ord(c) - FIRST][3] for c in "abcdefghijklmnopqrstuvwxyz"]
        print(f"  {f['name']}: line {f['yAdvance']}px, average lower-case advance "
              f"{sum(lower) / len(lower):.1f}px, widest {max(adv)}px")


if __name__ == "__main__":
    main()
